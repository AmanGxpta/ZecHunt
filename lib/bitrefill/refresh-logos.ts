// Read-only refresh of ./logos.generated.ts from Bitrefill REST GET /v2/products/{id}.
//   node --env-file=.env.local --import tsx lib/bitrefill/refresh-logos.ts
// Makes one GET per catalog brand and nothing else. Prints product ids and outcomes only,
// never the API key.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REWARD_CATALOG } from "./catalog";
import { logoSource, logoUrlFor, type LogoSource } from "./logos";

async function main(): Promise<void> {
  const apiKey = process.env.BITREFILL_API_KEY;
  if (!apiKey) throw new Error("BITREFILL_API_KEY is not set");

  const ids = [...new Set(REWARD_CATALOG.map((e) => e.productId))].sort();
  const logos: Record<string, LogoSource> = {};
  for (const id of ids) {
    const response = await fetch(`https://api.bitrefill.com/v2/products/${encodeURIComponent(id)}`, {
      method: "GET", headers: { authorization: `Bearer ${apiKey}`, accept: "application/json" },
      signal: AbortSignal.timeout(15_000),
    }).catch(() => null);
    const body = response?.ok ? await response.json().catch(() => null) as { data?: Record<string, unknown> } | null : null;
    const source = body?.data?.id === id ? logoSource(body.data.image, body.data.logo_background) : null;
    if (source && logoUrlFor(source)) logos[id] = source;
    console.log(`${source ? "ok     " : "missing"} ${id}${response && !response.ok ? ` (HTTP ${response.status})` : ""}`);
}

const out = join(__dirname, "logos.generated.ts");
writeFileSync(out, `// GENERATED by lib/bitrefill/refresh-logos.ts on ${new Date().toISOString().slice(0, 10)}. Read-only source:
// Bitrefill REST GET /v2/products/{id} (image, logo_background). Do not edit by hand.
import type { LogoSource } from "./logos";

export const CATALOG_LOGOS: Readonly<Record<string, LogoSource>> = ${JSON.stringify(logos, null, 2)};
`);
console.log(`${Object.keys(logos).length}/${ids.length} brands have a logo → ${out}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : "refresh failed");
  process.exit(1);
});
